def unescape_prop(s):
    return s.replace("\\:", ":").replace("\\n", "\n").replace("\\'", "'")

def translate_value(en_val):
    v = unescape_prop(en_val)
    if v in BY_VALUE:
        return BY_VALUE[v]
    for pat, ru, kz in MENU_MAP:
        if re.match(pat, v, re.IGNORECASE):
            return (ru, kz)
    for lookup in (v, v.strip()):
        if lookup in TITLE_MAP:
            ru, kz = TITLE_MAP[lookup]
            if v.startswith("  ") and not ru.startswith("  "):
                return ("  " + ru.lstrip(), "  " + kz.lstrip())
            return (ru, kz)
    return (v, v)

def load_en():
    data = {}
    with open(EN_FILE, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or "=" not in line:
                continue
            k, raw = line.split("=", 1)
            data[k] = raw
    return data

def escape_prop(s):
    return s.replace(":", "\\:").replace("\n", "\\n")

def write_file(path, data, lang_idx):
    lines = []
    for k in sorted(data.keys()):
        ru, kz = translate_value(unescape_prop(data[k]))
        lines.append(f"{k}={escape_prop(ru if lang_idx == 0 else kz)}")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

def main():
    en = load_en()
    write_file(os.path.join(BASE, "messages_ru.properties"), en, 0)
    write_file(os.path.join(BASE, "messages_kz.properties"), en, 1)
    # count untranslated (still same as EN)
    untranslated_ru = sum(1 for k, v in en.items() if translate_value(unescape_prop(v))[0] == unescape_prop(v))
    print(f"Done: {len(en)} keys. Still English in RU (approx): {untranslated_ru}")

if __name__ == "__main__":
    main()
